-- 식자재몰 시세 (S15P31A308-232, ADR-0010).
-- 크롤러(foodspring-crawler)가 매주 만드는 통합 데이터셋(7개 몰, 약 48만 줄)을 그대로 담는 전역 참조 표.
-- 가게 소속이 아니라 store_id 가 없다 — ADR-0002 가게 스코프의 유일한 예외(ADR-0010). 가게 스코프는 이 표를 읽는 쪽(재료 조회)이 건다.
-- 적재는 스냅샷 단위로 표 전체를 비우고 다시 넣는다(import-market-products 프로필). 열 뜻은 데이터셋 README 와 같다.
CREATE TABLE market_product (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site            VARCHAR(30) NOT NULL,          -- 사이트 (식봄 · 마켓컬리 · 농협몰 · 식자재왕몰 · 오아시스마켓 · 그리팅몰 · 아워홈몰)
    store_region    VARCHAR(50),                   -- 점포지역. 식자재왕몰은 점포마다 가격이 달라 점포마다 한 줄
    seller          VARCHAR(150),                  -- 판매자 (식봄 입점사)
    product_no      VARCHAR(50) NOT NULL,          -- 사이트가 준 상품번호. 식자재왕몰은 점포마다 따로 매긴다
    product_name    VARCHAR(300) NOT NULL,
    brand           VARCHAR(150),
    spec            VARCHAR(300),                  -- 규격 글자 그대로 ("1.8kg (60gx30)")
    price           BIGINT NOT NULL,               -- 판매가 (원)
    original_price  BIGINT,                        -- 할인 전 값. 없으면 NULL
    total_qty       NUMERIC(18, 3),                -- 규격(없으면 상품명)에서 읽은 총량. 해석 못 하면 NULL
    unit            VARCHAR(5),                    -- g · ml · 개. total_qty 와 같이 NULL
    unit_price_100  NUMERIC(16, 4),                -- 원/100g · 원/100ml, 개 단위는 원/개. 해석 못 하면 NULL (약 25%)
    category        VARCHAR(200),                  -- 사이트별 분류. 체계가 사이트마다 달라 통합 필터로 쓰지 않는다
    url             VARCHAR(500) NOT NULL,
    collected_on    DATE NOT NULL,                 -- 수집일
    group_no        BIGINT,                        -- 묶음번호: 두 사이트 이상에 같은 상품이면 같은 번호
    CONSTRAINT ck_market_product_unit CHECK (unit IS NULL OR unit IN ('g', 'ml', '개')),
    CONSTRAINT ck_market_product_price CHECK (price >= 0)
);

-- 상품명 검색은 부분 일치('%계란%' · 정규식)라 B-tree 를 못 탄다. 48만 줄 순차 읽기가 수백 ms 라 지금은 인덱스 없이 둔다(ADR-0010 "다시 볼 시점").
-- 사이트 안 같은 상품(점포 10곳) 접기와 최신 스냅샷 확인에 쓴다
CREATE INDEX idx_market_product_site_no ON market_product (site, product_no);
CREATE INDEX idx_market_product_collected_on ON market_product (collected_on);

COMMENT ON TABLE market_product IS '식자재몰 시세. 크롤러 통합 데이터셋(products_<날짜>.parquet) 스냅샷을 전체 교체로 적재한다. 가게 소속이 아닌 전역 참조 표(ADR-0010, ADR-0002 예외). 팀 내부 분석용 데이터라 밖으로 내보내지 않는다. 근거: S15P31A308-232.';
COMMENT ON COLUMN market_product.unit_price_100 IS '원/100g · 원/100ml, 개 단위면 원/개. 크롤러 units.py 가 계산한 값 그대로. 해석 실패는 NULL.';
COMMENT ON COLUMN market_product.group_no IS '크롤러 묶음번호. 브랜드 · 상품명 · 총량이 같은 상품이 두 사이트 이상에 있으면 같은 번호.';

-- 온보딩 저장본 (S15P31A308-321, ADR-0016).
-- 운영자가 미리 Apify 로 받아 둔 "가게 찾기 후보" · "메뉴 목록" 을 그대로 담는 전역 표. 시연에서 Apify 실시간 호출(10초~수 분)을 건너뛰는 데 쓴다.
-- 가게 소속이 아니라 store_id 가 없다 — ADR-0002 가게 스코프의 예외(ADR-0016, 선례 market_product ADR-0010). 가게 데이터를 담지 않고 공개된 검색 결과만 담는다.
-- 일반 요청은 이 표에 쓰지 않는다. 쓰기 · 지우기는 운영자 실행(onboarding-replay-save · onboarding-replay-delete 프로필)만 한다.
CREATE TABLE onboarding_replay (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         VARCHAR(10) NOT NULL,             -- SEARCH(가게 찾기 결과) | MENUS(메뉴 수집 결과)
    replay_key   VARCHAR(100) NOT NULL,            -- SEARCH 는 정규화한 검색어, MENUS 는 네이버 플레이스 id
    payload      JSONB NOT NULL,                   -- SEARCH 는 PlaceCandidate 목록, MENUS 는 CollectedMenu 목록 (변환 뒤 모양)
    captured_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_onboarding_replay_kind CHECK (kind IN ('SEARCH', 'MENUS')),
    CONSTRAINT uq_onboarding_replay_key UNIQUE (kind, replay_key)
);

COMMENT ON TABLE onboarding_replay IS '온보딩 저장본. 운영자가 미리 받아 둔 가게 찾기 후보 · 메뉴 목록. 있으면 Apify 를 부르지 않고 이것으로 응답한다. 가게 소속이 아닌 전역 표(ADR-0016, ADR-0002 예외). 지울 때까지 남는다. 근거: S15P31A308-321.';
COMMENT ON COLUMN onboarding_replay.kind IS 'SEARCH = GET /onboarding/places 결과, MENUS = 분석 job 의 메뉴 수집 결과.';
COMMENT ON COLUMN onboarding_replay.replay_key IS 'SEARCH 는 정규화한 검색어(앞뒤 공백 제거, 안쪽 연속 공백 한 칸, 대소문자 유지), MENUS 는 placeId.';
COMMENT ON COLUMN onboarding_replay.payload IS '변환 뒤 레코드 JSON 배열. SEARCH = PlaceCandidate[], MENUS = CollectedMenu[]. 변환 규칙이 바뀌어도 옛 결과가 남는다.';
COMMENT ON COLUMN onboarding_replay.captured_at IS 'Apify 에서 받아 저장한 시각. 같은 키를 다시 저장하면 갱신된다.';

-- 추천 생성 실행 기록 (S15P31A308-188, ADR-0009).
-- 추천(recommendation)은 발주가 필요한 재료만 남기므로, "오늘 계산을 끝냈다" 는 사실은 어디에도 남지 않았다.
-- 같은 날 다시 실행하면 발주 불필요 재료를 전부 다시 계산했다(재고 추정 · 예측 · 소비량 조회).
-- 가게 · 날짜마다 한 줄로 실행 사실과 결과 건수를 남겨, 그날 끝난 실행이 있으면 계산 없이 기존 추천만 돌려준다.
CREATE TABLE recommendation_run (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store(id),
    run_date        DATE NOT NULL,
    started_at      TIMESTAMPTZ NOT NULL,
    finished_at     TIMESTAMPTZ,            -- NULL 이면 끝나지 않은 실행. 끝난 실행만 건너뛰기의 근거가 된다
    created_count   INTEGER NOT NULL DEFAULT 0,
    no_order_count  INTEGER NOT NULL DEFAULT 0,
    -- 가게 · 날짜마다 한 줄. force=true 재계산은 같은 줄을 덮어쓴다
    CONSTRAINT uq_recommendation_run_store_date UNIQUE (store_id, run_date)
);

COMMENT ON TABLE recommendation_run IS '가게 · 날짜별 추천 생성 실행 기록. 그날 끝난 실행이 있으면 같은 날 재실행은 재고 추정 · 예측 · 소비량을 다시 조회하지 않고 기존 추천만 돌려준다. force=true 로 다시 계산하면 이 줄을 덮어쓴다. 근거: S15P31A308-188, ADR-0009.';
COMMENT ON COLUMN recommendation_run.started_at IS '마지막 실행(계산)을 시작한 시각.';
COMMENT ON COLUMN recommendation_run.finished_at IS '마지막 실행을 끝낸 시각. NULL 이면 끝나지 않은 실행이라 건너뛰기의 근거가 되지 않는다.';
COMMENT ON COLUMN recommendation_run.created_count IS '마지막 실행이 새로 만든 추천 수.';
COMMENT ON COLUMN recommendation_run.no_order_count IS '마지막 실행이 계산했지만 발주가 필요 없어 만들지 않은 재료 수.';

-- 재료 카테고리 (S15P31A308-273, DECISIONS #77).
-- 재료 탭이 냉장고 · 선반 · 창고 그림 안의 재료를 육류 · 채소 · 과일 · 소스 같은 카테고리로 걸러 보인다.
-- 카테고리는 가게별 표다 — 사장님이 새 카테고리를 만들고 지울 수 있어(후속 S15P31A308-275) enum 칸으로 두지 않는다.
-- 기본 11종은 가게마다 복사해 넣고 code 로 구분한다(사장님이 만든 것은 code NULL). '기타'(OTHER)는 가게마다 반드시 1개이고
-- 지우거나 이름을 바꾸지 못한다. 어느 카테고리에도 맞지 않는 재료는 '기타'.
-- 기본 목록의 정본은 DefaultIngredientCategory(Java) — 아래 VALUES 는 그 복사본이고, 바뀌면 새 마이그레이션으로 넣는다.
-- 기준: docs/plans/2026-11-06_재료_카테고리_분류_기준.md

-- 1. 가게별 카테고리 표
CREATE TABLE ingredient_category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id    BIGINT NOT NULL REFERENCES store(id),
    code        VARCHAR(20),                          -- 기본 카테고리 코드. 사장님이 만든 카테고리는 NULL
    name        VARCHAR(30) NOT NULL,
    sort_order  INT NOT NULL,                         -- 화면 순서. 기타는 맨 뒤(99)
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_ingredient_category_store_name UNIQUE (store_id, name),
    CONSTRAINT uq_ingredient_category_store_code UNIQUE (store_id, code),
    CONSTRAINT ck_ingredient_category_code CHECK (code IS NULL OR code IN (
        'MEAT', 'SEAFOOD', 'VEGETABLE', 'FRUIT', 'EGG_DAIRY', 'GRAIN_NOODLE', 'TOFU_BEAN', 'SAUCE', 'PROCESSED',
        'BEVERAGE', 'OTHER'))
);
COMMENT ON TABLE ingredient_category IS '재료 카테고리(가게별). 재료 탭의 필터 · 묶음 표시용. 기본 11종(code 있음)은 가게가 생길 때 복사해 넣고, 사장님이 만든 것은 code NULL. OTHER(기타)는 가게마다 1개 — 지우거나 이름을 바꾸지 못하고, 카테고리를 지우면 그 재료는 기타로 옮긴다. 근거: S15P31A308-273, DECISIONS #77.';
COMMENT ON COLUMN ingredient_category.code IS '기본 카테고리 코드(DefaultIngredientCategory). NULL 이면 사장님이 만든 카테고리. OTHER 가 기타.';
COMMENT ON COLUMN ingredient_category.sort_order IS '화면 순서(오름차순). 기본 11종은 1~10 · 기타 99. 사장님이 만든 것은 만들 때 마지막 다음 번호.';

-- 2. 기존 가게 전부에 기본 11종
INSERT INTO ingredient_category (store_id, code, name, sort_order)
SELECT s.id, d.code, d.name, d.sort_order
FROM store s
CROSS JOIN (VALUES
    ('MEAT',         '육류',        1),
    ('SEAFOOD',      '수산',        2),
    ('VEGETABLE',    '채소',        3),
    ('FRUIT',        '과일',        4),
    ('EGG_DAIRY',    '계란·유제품', 5),
    ('GRAIN_NOODLE', '곡물·면·떡',  6),
    ('TOFU_BEAN',    '두부·콩',     7),
    ('SAUCE',        '양념·소스',   8),
    ('PROCESSED',    '가공식품',    9),
    ('BEVERAGE',     '음료',        10),
    ('OTHER',        '기타',        99)
) AS d(code, name, sort_order);

-- 3. 재료 ↔ 카테고리. 기존 재료는 전부 그 가게의 '기타' (자동 분류는 S15P31A308-274). DB 기본값 없음 — 넣는 쪽이 명시한다.
ALTER TABLE ingredient ADD COLUMN category_id BIGINT REFERENCES ingredient_category(id);

UPDATE ingredient i
SET category_id = c.id
FROM ingredient_category c
WHERE c.store_id = i.store_id AND c.code = 'OTHER';

ALTER TABLE ingredient ALTER COLUMN category_id SET NOT NULL;

CREATE INDEX idx_ingredient_store_category ON ingredient(store_id, category_id);

COMMENT ON COLUMN ingredient.category_id IS '재료 카테고리(같은 가게의 ingredient_category). 만들 때 정하지 않으면 기타 — 자동 분류(S15P31A308-274)가 채운다. 계산에는 쓰지 않는다 (S15P31A308-273).';

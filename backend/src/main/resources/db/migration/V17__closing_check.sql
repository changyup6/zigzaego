-- 마감 재고 확인 · 손실 기록 · 웹 푸시 (S15P31A308-246, DECISIONS #88)
-- 1) 판매 없이 사라진 재고(빼기 기록) 2) 요일별 마감 시각 3) 웹 푸시 구독

CREATE TABLE stock_adjustment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store(id),
    ingredient_id   BIGINT NOT NULL REFERENCES ingredient(id),
    adjusted_at     TIMESTAMPTZ NOT NULL,
    qty             NUMERIC(14, 3) NOT NULL CHECK (qty > 0),
    reason          VARCHAR(10) NOT NULL CHECK (reason IN ('DISCARD', 'SPOILED', 'DAMAGED', 'SPILLED', 'OTHER')),
    memo            TEXT,
    before_qty      NUMERIC(14, 3) NOT NULL,
    after_qty       NUMERIC(14, 3) NOT NULL,
    source_text     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_stock_adjustment_store_ingredient_time ON stock_adjustment(store_id, ingredient_id, adjusted_at DESC);

COMMENT ON TABLE stock_adjustment IS '판매 없이 사라진 재고(빼기 기록). 사장님이 마감 확인 때 말한 버린 양만 적는다 — 손실을 추정하지 않는다(DECISIONS #88 ⑥ · #30). 추정 재고는 마지막 실사 이후의 빼기 합을 뺀다';
COMMENT ON COLUMN stock_adjustment.store_id IS '가게. 모든 조회 · 쓰기는 로그인한 계정의 가게로 강제(ADR-0002)';
COMMENT ON COLUMN stock_adjustment.ingredient_id IS '뺀 재료';
COMMENT ON COLUMN stock_adjustment.adjusted_at IS '뺀 시각. 같은 요청의 실사보다 앞서도록 저장 시각 − 1초로 넣는다';
COMMENT ON COLUMN stock_adjustment.qty IS '뺀 양. 양수 · 재료 기준 단위(g · ml · 개). 포장 단위로 말한 양은 base_qty_per_pack 으로 바꿔 넣는다';
COMMENT ON COLUMN stock_adjustment.reason IS '사유 5종: DISCARD 폐기 · SPOILED 상함 · DAMAGED 파손 · SPILLED 쏟음 · OTHER 기타';
COMMENT ON COLUMN stock_adjustment.memo IS '사장님 메모. 없어도 된다';
COMMENT ON COLUMN stock_adjustment.before_qty IS '빼기 직전 추정 재고(기준 단위)';
COMMENT ON COLUMN stock_adjustment.after_qty IS '빼기 직후 추정 재고(기준 단위). 0 아래로 내려가면 0';
COMMENT ON COLUMN stock_adjustment.source_text IS '자유 입력 원문(글 또는 음성을 글로 바꾼 것). 직접 고른 줄은 NULL';
COMMENT ON COLUMN stock_adjustment.created_at IS '줄을 만든 시각';

CREATE TABLE store_closing_time (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store(id),
    day_of_week     SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    close_time      TIME NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_store_closing_time_store_day UNIQUE (store_id, day_of_week)
);

COMMENT ON TABLE store_closing_time IS '요일별 마감 시각(DECISIONS #88 ①). 줄이 없는 요일은 휴무 또는 미설정 — 그날은 마감 확인 알림을 보내지 않는다';
COMMENT ON COLUMN store_closing_time.store_id IS '가게';
COMMENT ON COLUMN store_closing_time.day_of_week IS '요일. ISO 순서 월=1 … 일=7. 종료 시각이 자정을 넘으면 영업을 시작한 요일 줄에 넣는다';
COMMENT ON COLUMN store_closing_time.close_time IS '영업 종료 시각. 가게 시간대(store.timezone) 기준';
COMMENT ON COLUMN store_closing_time.created_at IS '줄을 만든 시각';
COMMENT ON COLUMN store_closing_time.updated_at IS '마지막으로 고친 시각';

ALTER TABLE stock_count ADD COLUMN counted_after_close BOOLEAN NOT NULL DEFAULT false;
COMMENT ON COLUMN stock_count.counted_after_close IS '마감 확인에서 센 실사면 true. 그날 판매가 끝난 뒤의 값이라 추정 재고는 다음 날 판매부터 뺀다. false 는 영업 시작 전 값(그날 판매부터 뺀다)';

ALTER TABLE store ADD COLUMN last_closing_push_date DATE;
COMMENT ON COLUMN store.last_closing_push_date IS '마감 확인 알림을 마지막으로 보낸 영업일(가게 시간대). 같은 날 두 번 보내지 않기 위한 표시. 보낸 적 없으면 NULL';

CREATE TABLE push_subscription (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store(id),
    user_id         BIGINT NOT NULL REFERENCES account(id),
    endpoint        TEXT NOT NULL,
    p256dh          TEXT NOT NULL,
    auth            TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_push_subscription_endpoint UNIQUE (endpoint)
);
CREATE INDEX idx_push_subscription_store ON push_subscription(store_id);

COMMENT ON TABLE push_subscription IS '웹 푸시 구독(브라우저 · 기기 하나에 한 줄). 마감 확인 알림만 보낸다(DECISIONS #88). 푸시 서버가 404 · 410 을 주면 지운다';
COMMENT ON COLUMN push_subscription.store_id IS '알림을 받을 가게';
COMMENT ON COLUMN push_subscription.user_id IS '구독한 계정(account.id)';
COMMENT ON COLUMN push_subscription.endpoint IS '푸시 서비스 주소(PushSubscription.endpoint). 기기마다 달라 unique — 같은 주소로 다시 구독하면 줄을 갱신한다';
COMMENT ON COLUMN push_subscription.p256dh IS '구독 공개키(keys.p256dh, base64url). 알림 본문 암호화에 쓴다';
COMMENT ON COLUMN push_subscription.auth IS '구독 인증 비밀값(keys.auth, base64url)';
COMMENT ON COLUMN push_subscription.created_at IS '줄을 만든 시각';

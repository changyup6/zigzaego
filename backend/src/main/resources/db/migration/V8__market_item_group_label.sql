-- 식자재몰 품목군 기준표 · 상품명 라벨 · 일별 시세 이력 (S15P31A308-228 · 229, ADR-0012).
-- 상품명 글자 매칭 대신 "품목군(계란 ≠ 액란 ≠ 구운란)" 을 미리 붙여 두고, 플랫폼별 최저가와 일별 추이를 품목군 × 사이트 × 수집일로 집계한다.
-- 기준: docs/plans/2026-11-03_식자재몰_품목군_분류_기준.md. 품목군 표의 정본은 ai/seed/market_item_group.csv — 바뀌면 새 마이그레이션으로 넣는다.

-- 1. 품목군 기준표 (전역 참조 표, ADR-0002 예외 셋째)
CREATE TABLE market_item_group (
    code              VARCHAR(40) PRIMARY KEY,       -- 영문 대문자 코드 (EGG · EGG_LIQUID · PORK_BELLY …). 이름이 바뀌어도 코드는 그대로
    name              VARCHAR(50) NOT NULL,          -- 화면 이름
    parent_code       VARCHAR(40) REFERENCES market_item_group (code),  -- 부위 → 종 (PORK_BELLY → PORK)
    category          VARCHAR(20) NOT NULL,          -- 채소 · 과일 · 육류 · 계란 · 수산 · 유제품 · …
    comparable        BOOLEAN NOT NULL DEFAULT true, -- false = 부모(돼지고기 · 소고기 · 닭고기 · 치즈). 최저가 · 추이를 내지 않는다
    base_unit         VARCHAR(2) NOT NULL,           -- 값을 비교하는 기준 단위 G · ML · EA
    ea_weight_g       NUMERIC(10, 3),                -- 1개 무게(g). 개 ↔ g 환산. NULL 이면 환산하지 않는다
    density_g_per_ml  NUMERIC(6, 3),                 -- 밀도. g ↔ ml 환산. NULL 이면 환산하지 않는다
    aliases           TEXT NOT NULL,                 -- 이름 · 이명 (';' 구분). 재료 이름 → 품목군 매핑에만 쓴다
    note              VARCHAR(300),
    CONSTRAINT ck_market_item_group_unit CHECK (base_unit IN ('G', 'ML', 'EA'))
);
COMMENT ON TABLE market_item_group IS '식자재몰 품목군 기준표. 사장님이 발주할 때 서로 바꿔 쓸 수 있고 같은 기준 단위로 값을 비교할 수 있는 상품 묶음(계란 ≠ 액란, 두부 ≠ 순두부). 정본은 ai/seed/market_item_group.csv (ADR-0012). 근거: S15P31A308-228 · 229.';
COMMENT ON COLUMN market_item_group.aliases IS '이름 · 이명(";" 구분). 재료 이름(ingredient.name)이 이 중 하나와 같으면(공백 무시) 그 품목군. 상품이 품목군에 드는지는 라벨(market_product_label)이 정한다.';

-- 2. 상품명 라벨 (LLM 배치 결과, ai/scripts/market/classify_products.py). 라벨의 키 = 상품명 — 같은 이름은 어느 사이트 · 수집일이든 같은 라벨
CREATE TABLE market_product_label (
    product_name      VARCHAR(300) PRIMARY KEY,
    item_group_code   VARCHAR(40) REFERENCES market_item_group (code),  -- 원물 · 손질품으로서 속한 품목군. 가공품 · 비식품은 NULL
    form              VARCHAR(10) NOT NULL,          -- RAW · PREPARED · PROCESSED · NONFOOD · UNKNOWN
    qty               NUMERIC(18, 3),                -- 상품명에서 읽은 전체 총량 (규격 해석이 없을 때 보조)
    qty_unit          VARCHAR(2),                    -- G · ML · EA
    confidence        NUMERIC(4, 3) NOT NULL,        -- 품목군 판정 확신 0~1. 0.6 미만은 집계에서 UNKNOWN 취급
    reason            VARCHAR(100),
    label_version     VARCHAR(20) NOT NULL,          -- 프롬프트 · 표 · 모델 버전. 바뀌면 다시 분류
    labeled_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_market_product_label_form CHECK (form IN ('RAW', 'PREPARED', 'PROCESSED', 'NONFOOD', 'UNKNOWN')),
    CONSTRAINT ck_market_product_label_unit CHECK (qty_unit IS NULL OR qty_unit IN ('G', 'ML', 'EA')),
    CONSTRAINT ck_market_product_label_code CHECK (item_group_code IS NULL OR form IN ('RAW', 'PREPARED'))
);
CREATE INDEX idx_market_product_label_group ON market_product_label (item_group_code) WHERE item_group_code IS NOT NULL;
COMMENT ON TABLE market_product_label IS '식자재몰 상품명 → 품목군 · 형태 라벨. LLM 배치가 만든 CSV(labels.csv)를 import-market-products 프로필이 upsert 한다. 라벨 없는 상품명은 규칙(ItemMatcher)으로 임시 판정한다 (ADR-0012). 근거: S15P31A308-229.';

-- 3. 시세 표는 이제 수집일마다 쌓인다(ADR-0010 의 "전체 교체" → 같은 수집일 줄만 교체). 라벨 조인과 날짜 범위 조회용 인덱스
CREATE INDEX idx_market_product_name ON market_product (product_name);
CREATE INDEX idx_market_product_site_collected ON market_product (site, collected_on);
COMMENT ON TABLE market_product IS '식자재몰 시세. 크롤러 통합 데이터셋(products_<날짜>.parquet)을 수집일 단위로 쌓는다 — 적재는 파일에 든 수집일의 줄만 지우고 다시 넣는다(ADR-0012, 이전 ADR-0010 은 전체 교체). 가게 소속이 아닌 전역 참조 표(ADR-0002 예외). 팀 내부 분석용 데이터라 밖으로 내보내지 않는다. 근거: S15P31A308-232 · 229.';


-- 사장님 가게 위치로 배달 가능한 판매처 판정 (S15P31A308-230, ADR-0011).
-- 식자재몰 최저가(market_product, ADR-0010)는 7개 몰이 전부 나왔다. 식봄은 서울 중구에만, 식자재왕몰은 점포 주변에만 배달하므로
-- 가게 위치와 몰의 배송 지역을 맞춰 배달 안 되는 판매처를 빼야 한다.

-- 1. 가게 위치 = 시군구 한 칸. "<시도> <시군구>" 꼴의 글자 그대로('서울 중구' · '경기 성남시'). NULL 이면 위치 미설정 → 모든 판매처가 '확인 필요'.
ALTER TABLE store ADD COLUMN sigungu VARCHAR(50);
COMMENT ON COLUMN store.sigungu IS '가게가 있는 시군구("<시도> <시군구>", 예 "서울 중구"). 식자재몰 배송 지역(market_site_delivery_area.sigungu)과 글자 그대로 맞춘다. NULL 이면 위치를 아직 안 받은 것이라 배달 가능 여부를 판정하지 않는다. 근거: S15P31A308-230.';

-- 2. 판매처별 배송 가능 지역. 가게 소속이 아닌 전역 참조 표(ADR-0002 예외, ADR-0011).
--    한 줄 = "이 사이트(의 이 점포)가 이 시군구에 배달한다". 사이트에 줄이 하나도 없으면 배송 지역을 모르는 것 → '확인 필요'.
CREATE TABLE market_site_delivery_area (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site            VARCHAR(30) NOT NULL,          -- market_product.site 와 같은 이름
    store_region    VARCHAR(50),                   -- market_product.store_region 과 맞추는 점포명(식자재왕몰 '상일점'). NULL 이면 그 사이트 모든 줄
    sigungu         VARCHAR(50),                   -- 배달하는 시군구. NULL 이면 전국
    dawn_delivery   BOOLEAN,                       -- 새벽배송 여부. NULL 이면 모름
    CONSTRAINT uq_market_site_delivery_area UNIQUE NULLS NOT DISTINCT (site, store_region, sigungu)
);

COMMENT ON TABLE market_site_delivery_area IS '식자재몰(점포)별 배달 가능 시군구. 가게 소속이 아닌 전역 참조 표(ADR-0011, ADR-0002 예외). 사이트에 줄이 없으면 배송 지역을 몰라 재료 최저가 응답의 deliveryUnknown 에 들어간다. 크롤러 데이터셋에서 확인한 범위만 시드로 넣고 나머지는 운영자가 마이그레이션으로 보탠다. 근거: S15P31A308-230.';
COMMENT ON COLUMN market_site_delivery_area.store_region IS 'market_product.store_region 과 글자 그대로 맞추는 점포명. NULL 이면 사이트 전체에 적용.';
COMMENT ON COLUMN market_site_delivery_area.sigungu IS '배달하는 시군구("<시도> <시군구>"). NULL 이면 전국 배송.';
COMMENT ON COLUMN market_site_delivery_area.dawn_delivery IS '새벽배송 여부. NULL 이면 확인 안 됨.';


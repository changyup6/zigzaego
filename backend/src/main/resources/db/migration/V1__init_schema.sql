-- 3. 매입 문서와 단가 이력
--    사장님은 우리 앱 밖에서 이미 매입 문서를 받는다. 그 문서를 담아야 단가 이력·
--    입고 대사(우리 발주서와 맞춰 보기)·레시피 역산이 된다. 이 MR 은 표 구조까지만 — OCR·파서 코드는 별도 일감(지라 111·112, 설계 4절)
--    설계의 receipt = purchase_doc, receipt_line = purchase_doc_line (설계 7절. 이름은 바꾸지 않는다)
-- =====================================================================

-- 몇 분 걸리는 작업 하나(온보딩 분석·영수증 인식). 화면이 진행률을 물어본다.
-- purchase_doc.job_id 가 이 표를 가리켜 job 을 먼저 만든다 (설계 2.4·4.2·7절)
CREATE TABLE job (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store(id),
    type            VARCHAR(12) NOT NULL CHECK (type IN ('ONBOARDING', 'RECEIPT')),
    -- 서버 재시작 시 RUNNING 인 job 은 FAILED 로 바꾸고 화면에 재시도 버튼 (설계 7절)
    status          VARCHAR(10) NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    progress        NUMERIC(4, 3) NOT NULL DEFAULT 0 CHECK (progress >= 0 AND progress <= 1),  -- 0~1
    -- 온보딩 분석 결과(메뉴·재료·레시피·조합 규칙·질문)는 사장님이 확정할 때까지 여기에만 둔다 (설계 2.4절)
    result_json     JSONB,
    error           TEXT,  -- 실패 사유
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at     TIMESTAMPTZ  -- DONE·FAILED 가 된 시각
);
CREATE INDEX idx_job_store_created ON job(store_id, created_at DESC);
CREATE INDEX idx_job_status ON job(status);

CREATE TABLE purchase_doc (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id            BIGINT NOT NULL REFERENCES store(id),
    supplier_id         BIGINT REFERENCES supplier(id),  -- NULL 허용: 마트 영수증처럼 등록 안 된 곳에서 산 경우
    -- 문서 종류 10개. 사장님 사용 빈도 예상 순서대로 (실험/poc/feasibility.py:55-66):
    -- 거래명세서·납품서(매우 높음) · 구매 영수증(매우 높음) · 카톡·문자 발주내역(높음) · 온라인 식자재몰 주문내역(높음) ·
    -- 전자세금계산서(높음) · 발주서(중간) · 거래원장·매입장(중간) · 견적서·단가표(중간~낮음) · 재고관리표(편차 큼) · POS·ERP 매입기록(편차 큼)
    -- doc_type·doc_date 는 NULL 허용: 올린 직후(인식 전)엔 모른다 (설계 4.2절)
    doc_type            VARCHAR(20) CHECK (doc_type IN (
                            'STATEMENT', 'RECEIPT', 'KAKAO', 'MALL_ORDER', 'TAX_INVOICE',
                            'ORDER_FORM', 'LEDGER', 'QUOTE', 'STOCK_SHEET', 'POS_ERP')),
    doc_date            DATE,
    total_amount        NUMERIC(12, 2),  -- 합계가 안 읽히는 문서도 있어 NULL 허용
    file_path           VARCHAR(500),    -- 원본 사진·파일 위치
    -- PENDING=올림 / PROCESSING=인식 중 / PARSED=자동으로 읽음 / CONFIRMED=사장님 확인 / FAILED=못 읽음
    parse_status        VARCHAR(10) NOT NULL
                            CHECK (parse_status IN ('PENDING', 'PROCESSING', 'PARSED', 'CONFIRMED', 'FAILED')),
    -- 우리 발주서와 연결되면 입고 대사. 연결된 문서의 줄은 발주서 입고(received_qty)와 중복이라 재고에 더하지 않는다 (DECISIONS #41)
    -- 비어 있으면 문서 CONFIRMED · kind=RECEIVE · 줄 ingredient_id 있음 · 줄 status='CONFIRMED' 인 줄만 재고에 더한다
    purchase_order_id   BIGINT REFERENCES purchase_order(id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    job_id              BIGINT REFERENCES job(id),  -- 이 문서를 처리한 영수증 job. 직접 넣은 문서는 NULL (설계 4.2절)
    ocr_json            JSONB,  -- OCR 원문 결과 그대로
    -- PAST=재고 실사일 이전(재고에 안 더함, 가격·주기형 속도에만) / RECEIVE=이후(위 규칙의 확인된 줄만 재고에 더함, DECISIONS #41). 날짜를 읽기 전엔 NULL (설계 4.2·4.3절)
    kind                VARCHAR(10) CHECK (kind IN ('PAST', 'RECEIVE')),
    error               TEXT  -- 이 장의 실패 사유. 실패한 장만 재시도·삭제하고 나머지는 계속 처리 (설계 4.4절)
);
CREATE INDEX idx_purchase_doc_store_date ON purchase_doc(store_id, doc_date);
CREATE INDEX idx_purchase_doc_supplier ON purchase_doc(supplier_id);
CREATE INDEX idx_purchase_doc_job ON purchase_doc(job_id);


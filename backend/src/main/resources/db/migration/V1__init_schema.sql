CREATE TABLE store (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    display_name    VARCHAR(100) NOT NULL,
    timezone        VARCHAR(50) NOT NULL DEFAULT 'Asia/Seoul',
    onboarding      JSONB NOT NULL DEFAULT '{}'::jsonb,  -- pos/menu/recipe/supplier/count 완료 여부
    -- 자동 세팅(온보딩) 수집 소스. 네이버 플레이스 ID·요기요 가게 ID 로 메뉴·설명·사진을 가져온다 (설계 2·7절)
    naver_place_id  VARCHAR(50),
    yogiyo_shop_id  VARCHAR(50),
    yogiyo_consent  BOOLEAN NOT NULL DEFAULT false,  -- 사장님이 요기요 수집에 동의했는지. 동의 전엔 요기요를 부르지 않는다
    -- 포스기 API 로 어느 업체(pos_vendor)의 어느 매장(pos_store_code) 판매를 가져올지.
    -- 접속 키·비밀번호는 DB 에 두지 않는다 — 서버 환경 변수로 둔다
    pos_vendor      VARCHAR(30),
    pos_store_code  VARCHAR(100)
);

CREATE TABLE account (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    name            VARCHAR(100) NOT NULL,
    CONSTRAINT uq_account_email UNIQUE (email)
);

CREATE TABLE store_member (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT NOT NULL REFERENCES account(id),
    store_id    BIGINT NOT NULL REFERENCES store(id),
    role        VARCHAR(10) NOT NULL CHECK (role IN ('OWNER', 'STAFF')),
    CONSTRAINT uq_store_member UNIQUE (account_id, store_id)
    -- ADR-0002 본문은 이 표를 account_store로 부르지만, 3주_개발_계획.md 5절의 실제 칼럼 정의(store_member)를 따른다
);
CREATE INDEX idx_store_member_store ON store_member(store_id);

-- =====================================================================
-- 2. 가게 소속 테이블 — 전부 store_id NOT NULL (ADR-0002)
-- =====================================================================

CREATE TABLE menu (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id                BIGINT NOT NULL REFERENCES store(id),
    name                    VARCHAR(100) NOT NULL,
    -- 포스에 찍히는 이름은 여러 개일 수 있어 menu_alias 표로 옮겼다 (DECISIONS #40)
    -- MAIN=일반 메뉴 / OPTION=유료 추가 옵션("마늘 추가" — 레시피 줄을 단다) / SET=세트(구성은 menu_component)
    kind                    VARCHAR(10) NOT NULL DEFAULT 'MAIN' CHECK (kind IN ('MAIN', 'OPTION', 'SET')),
    active                  BOOLEAN NOT NULL DEFAULT true,
    price                   NUMERIC(12, 2),  -- 판매가. 메뉴판 OCR(온보딩 1단계)·네이버 플레이스로 메뉴를 맞출 때 이름과 함께 쓴다
    description             TEXT,  -- 수집한 메뉴 설명. LLM 구성 추출의 입력 — 설명이 없는 메뉴만 사진을 보낸다 (설계 2.4절)
    -- 이 메뉴를 어디서 가져왔나. DB 기본값 없음 — 넣는 쪽이 명시한다 (설계 7절)
    source                  VARCHAR(12) NOT NULL CHECK (source IN ('NAVER', 'YOGIYO', 'POS', 'MENU_PHOTO')),
    CONSTRAINT uq_menu_store_name UNIQUE (store_id, name)
);

-- 세트 하나가 어떤 메뉴 몇 개로 이뤄지는지. 고르는 구성(사이드·음료 선택)은 여기 넣지 않고 포스 원본 줄의 옵션으로 받는다
CREATE TABLE menu_component (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id            BIGINT NOT NULL REFERENCES store(id),
    set_menu_id         BIGINT NOT NULL REFERENCES menu(id),  -- kind='SET' 인 메뉴여야 한다(DB 는 검사 안 함 — 서버가 검사)
    component_menu_id   BIGINT NOT NULL REFERENCES menu(id),  -- 세트에 들어가는 메뉴
    qty                 NUMERIC(14, 3) NOT NULL CHECK (qty > 0),
    CONSTRAINT uq_menu_component_set_component UNIQUE (set_menu_id, component_menu_id),
    CONSTRAINT ck_menu_component_not_self CHECK (set_menu_id <> component_menu_id)
);
CREATE INDEX idx_menu_component_component ON menu_component(component_menu_id);

-- 포스기에 찍히는 이름 여러 개 → 우리 메뉴 하나. 예전 menu.pos_name(이름 하나)을 대신한다
CREATE TABLE menu_alias (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id    BIGINT NOT NULL REFERENCES store(id),
    menu_id     BIGINT NOT NULL REFERENCES menu(id),
    pos_name    VARCHAR(150) NOT NULL,
    CONSTRAINT uq_menu_alias_store_pos_name UNIQUE (store_id, pos_name)
);
CREATE INDEX idx_menu_alias_menu ON menu_alias(menu_id);

-- 가게가 쉰 날. 요일 평균 예측(DECISIONS #24 의 대체값, 3주 계획 4.3 "휴무일 제외")에서 판매 0 인 날과 쉰 날을 구분한다
CREATE TABLE store_closed_day (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id    BIGINT NOT NULL REFERENCES store(id),
    closed_date DATE NOT NULL,
    reason      VARCHAR(100),
    CONSTRAINT uq_store_closed_day_store_date UNIQUE (store_id, closed_date)
);

CREATE TABLE ingredient (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id                    BIGINT NOT NULL REFERENCES store(id),
    name                        VARCHAR(100) NOT NULL,
    -- 기준 단위: EA(개) / G / ML. 재고·레시피·소비량은 전부 이 단위. 보조 단위·환산은 만들지 않는다 (설계 3절)
    unit                        VARCHAR(20) NOT NULL CHECK (unit IN ('EA', 'G', 'ML')),
    safety_days                NUMERIC(6, 2) NOT NULL DEFAULT 1,  -- 안전재고 배수 N. DAYS_N 식(최근 7일 평균 × N일 — 소비 이력 28일 미만·주기형)에서만 쓴다 (DECISIONS #28)
    max_order_qty               NUMERIC(14, 3),
    primary_supplier_product_id BIGINT,  -- FK는 supplier_product 생성 뒤 ALTER로 건다 (순환 참조, 아래 참고)
    price_sensitive             BOOLEAN NOT NULL,
    -- 보관 방식(storage_type)으로 기본값을 고른다: 신선 false · 냉동/상온 true (3주_개발_계획.md:223, 지라 101).
    -- DB 기본값은 두지 않음 — 입력 시점(온보딩·시드)에 명시적으로 넣는다
    shelf_life_days             INTEGER,
    -- 범용(GENERIC: 파스타면·음료 같은 기성품, 업체·가격이 자주 바뀜) / 전용(DEDICATED: 가게 전용 제휴품, 거의 고정).
    -- 재료 자체의 성질이라 재료 표에 둔다 (2026-10-07 위글리 미팅). price_sensitive 와 같이 DB 기본값 없음 — 입력 시점에 명시
    sourcing_type               VARCHAR(10) NOT NULL CHECK (sourcing_type IN ('GENERIC', 'DEDICATED')),
    -- 재료 종류: BOM(메뉴 판매 × 1인분) / ONE_TO_ONE(사 온 그대로 팜) / CYCLE(주기형, 입고 기록으로만 소진 계산).
    -- DB 기본값 없음 — 넣는 쪽이 명시 (설계 4.1절)
    kind                        VARCHAR(12) NOT NULL CHECK (kind IN ('BOM', 'ONE_TO_ONE', 'CYCLE')),
    -- 단위 상태: ESTIMATED(LLM 추정) → CONFIRMED(사장님 답) → LOCKED(그 단위로 입고 기록이 생겨 고정) (설계 3.1절)
    unit_status                 VARCHAR(10) NOT NULL DEFAULT 'ESTIMATED'
                                    CHECK (unit_status IN ('ESTIMATED', 'CONFIRMED', 'LOCKED')),
    -- 보관 방식: 냉동·상온·냉장·신선. 안전재고 z·유통기한·가격 연동 기본값을 고르는 기준. DB 기본값 없음 (설계 5.3절)
    -- BOM·1:1 은 필수(아래 ck_ingredient_storage_type_required). 주기형(CYCLE)은 모르면 NULL — 안전재고는 "7일 평균 × N일"이라 없어도 돈다
    storage_type                VARCHAR(10) CHECK (storage_type IN ('FROZEN', 'AMBIENT', 'CHILLED', 'FRESH')),
    CONSTRAINT uq_ingredient_store_name UNIQUE (store_id, name),
    CONSTRAINT ck_ingredient_storage_type_required CHECK (kind = 'CYCLE' OR storage_type IS NOT NULL)
);

CREATE TABLE supplier (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id            BIGINT NOT NULL REFERENCES store(id),
    name                VARCHAR(100) NOT NULL,
    -- MALL = 식봄·쿠팡 같은 온라인 식자재몰 (2026-10-07 위글리 미팅: 주 거래처가 하루 배송 식자재몰)
    -- channel·lead_time_days·order_cycle_days 는 NULL 허용: 영수증으로 처음 생긴 거래처는 모른다.
    -- 발주 계산이 그 값을 쓸 때 화면이 사장님께 묻는 표시를 띄운다 (설계 6절). CHECK 는 값이 있을 때만 걸린다
    channel             VARCHAR(10) CHECK (channel IN ('KAKAO', 'PHONE', 'EMAIL', 'WEB', 'MALL')),
    lead_time_days      INTEGER,
    order_cycle_days    INTEGER,  -- R
    cutoff_time         TIME,
    delivery_days       TEXT[],  -- 요일 코드 배열, 예: {MON,WED,FRI}
    min_order_amount    NUMERIC(12, 2),
    message_template    TEXT,
    email               VARCHAR(255),
    -- 배송비와 무료배송 최소 금액. 2026-10-07 미팅(채널마다 가격이 다름)에서 가격을 비교할 때 배송비가 빠지면 결론이 뒤집혀 둔 칸.
    -- 3주 범위 가격 비교(DECISIONS #37: 같은 재료를 식봄·쿠팡 두 곳만)에서 쓸지는 조사(S15P31A308-122) 뒤 결정
    shipping_fee        NUMERIC(12, 2),
    free_shipping_min   NUMERIC(12, 2),
    CONSTRAINT uq_supplier_store_name UNIQUE (store_id, name)
);

CREATE TABLE supplier_product (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store(id),
    supplier_id     BIGINT NOT NULL REFERENCES supplier(id),
    ingredient_id   BIGINT NOT NULL REFERENCES ingredient(id),
    product_name    VARCHAR(150) NOT NULL,
    -- pack_size·pack_unit·moq·price 는 NULL 허용: 영수증으로 처음 생긴 상품은 모른다 (설계 6절)
    pack_size       NUMERIC(14, 3),
    pack_unit       VARCHAR(20),
    moq             NUMERIC(14, 3),
    price           NUMERIC(12, 2),  -- 현재 단가. 바뀌면 price_history에 기록
    -- 포장 1개 = 재료 기준 단위 몇 (대파 1단 → 1000 g). 모르면 NULL (설계 3절)
    base_qty_per_pack NUMERIC(14, 3) CHECK (base_qty_per_pack > 0),
    -- 한 거래처 안에서 같은 상품명은 한 줄 (매입 문서 줄에서 상품을 이름으로 찾는다)
    CONSTRAINT uq_supplier_product_supplier_name UNIQUE (supplier_id, product_name)
);
CREATE INDEX idx_supplier_product_supplier ON supplier_product(supplier_id);
CREATE INDEX idx_supplier_product_ingredient ON supplier_product(ingredient_id);

-- ingredient ↔ supplier_product 순환 참조 해소: supplier_product가 생긴 뒤 FK를 건다
ALTER TABLE ingredient
    ADD CONSTRAINT fk_ingredient_primary_supplier_product
    FOREIGN KEY (primary_supplier_product_id) REFERENCES supplier_product(id);

CREATE TABLE recipe (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id            BIGINT NOT NULL REFERENCES store(id),
    menu_id             BIGINT NOT NULL REFERENCES menu(id),
    ingredient_id       BIGINT NOT NULL REFERENCES ingredient(id),
    qty_per_serving     NUMERIC(14, 4) NOT NULL,  -- 재료 기준 단위(ingredient.unit: EA·G·ML) 기준
    -- 이 양이 어디서 왔나: 사장님 입력 / AI 추정 / 객관식 질문으로 사장님 확인 / 매입·판매 역산 보정 / 레시피 파일 업로드(지라 97).
    -- 설계의 recipe.estimated = source='AI' (estimated 칸은 따로 두지 않는다).
    -- 기본값 MANUAL: 사장님 직접 입력. 온보딩 자동 세팅(DECISIONS #29)은 AI, 레시피 파일 업로드(지라 97)는 FILE 로 넣는 쪽이 명시한다
    source              VARCHAR(20) NOT NULL DEFAULT 'MANUAL'
                            CHECK (source IN ('MANUAL', 'AI', 'OWNER_CONFIRMED', 'REGRESSION', 'FILE')),
    -- AI 확신도 0~1. 온보딩 5단계 "확신 낮은 항목만 사장님께 질문" 의 선택 기준
    confidence          NUMERIC(4, 3) CHECK (confidence >= 0 AND confidence <= 1),
    CONSTRAINT uq_recipe_menu_ingredient UNIQUE (store_id, menu_id, ingredient_id)
);
CREATE INDEX idx_recipe_ingredient ON recipe(ingredient_id);

CREATE TABLE pos_sale (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store(id),
    sold_date       DATE NOT NULL,
    menu_id         BIGINT NOT NULL REFERENCES menu(id),
    qty             NUMERIC(14, 3) NOT NULL,
    raw_menu_name   VARCHAR(150),
    -- 판매가 어디서 들어왔나: 포스기 API 자동 수집 / 포스 엑셀 업로드.
    -- 2026-10-14 기획 방향(포스기 API)을 받을 칸만 미리 둔다. 3주 안의 입력은 여전히 엑셀 (DECISIONS #3, #39)
    source          VARCHAR(10) NOT NULL DEFAULT 'EXCEL' CHECK (source IN ('API', 'EXCEL')),
    source_file     VARCHAR(255),  -- 엑셀 업로드일 때만. API 로 들어오면 NULL
    -- 판매 채널: DELIVERY(배달) / HALL(홀) / NONE(포스에 구분 없음, 기본값). 예측을 채널별로 따로 낸다 (설계 5.2·7절)
    channel         VARCHAR(10) NOT NULL DEFAULT 'NONE' CHECK (channel IN ('DELIVERY', 'HALL', 'NONE')),
    -- 하루·메뉴·채널별 합계 한 줄 — 예측(4.3)이 하루 단위라서 이 unique 를 유지한다.
    -- 원본 줄(pos_sale_line)이 있으면 그것을 하루·메뉴·채널로 합친 요약이고, 엑셀 합계만 받는 가게는 직접 넣는다 (DECISIONS #40)
    CONSTRAINT uq_pos_sale_store_date_menu_channel UNIQUE (store_id, sold_date, menu_id, channel)
);
CREATE INDEX idx_pos_sale_store_date ON pos_sale(store_id, sold_date);

-- 포스기 판매를 영수증 한 줄씩 그대로 보관. 하루 합계로 합치면 옵션이 어느 본품에 붙었는지가 사라져 되살릴 수 없다.
-- 0원 옵션(빼기)·면 변경·곱빼기 같은 계산 규칙은 포스 형식을 모르니 넣지 않는다 — 이 원본 줄로 나중에 다시 계산한다
CREATE TABLE pos_sale_line (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store(id),
    sold_at         TIMESTAMPTZ NOT NULL,
    sold_date       DATE NOT NULL,          -- 영업일(포스가 주는 날짜). 영수증 번호가 날마다 다시 시작해도 구분되게 unique 에 넣는다
    receipt_no      VARCHAR(100) NOT NULL,  -- 포스 영수증 번호
    line_no         INTEGER NOT NULL,       -- 영수증 안 줄 번호
    parent_line_id  BIGINT REFERENCES pos_sale_line(id),  -- 옵션 줄이면 붙은 본품 줄. 본품 줄은 NULL. 같은 가게·같은 영수증(영업일 sold_date + receipt_no 둘 다 같음)·자기 자신 아님은 서버가 검사
    raw_name        VARCHAR(150) NOT NULL,  -- 포스에 찍힌 이름 그대로
    qty             NUMERIC(14, 3) NOT NULL,
    amount          NUMERIC(12, 2),
    menu_id         BIGINT REFERENCES menu(id),  -- 메뉴와 연결 전이면 NULL (menu_alias 로 연결)
    source          VARCHAR(10) NOT NULL DEFAULT 'EXCEL' CHECK (source IN ('API', 'EXCEL')),
    raw             JSONB,  -- 포스 원본 한 줄 그대로
    -- 이 줄의 판매 채널. unique 에는 넣지 않는다 — 영수증 한 줄은 채널과 무관하게 하나 (설계 7절)
    channel         VARCHAR(10) NOT NULL DEFAULT 'NONE' CHECK (channel IN ('DELIVERY', 'HALL', 'NONE')),
    CONSTRAINT uq_pos_sale_line_store_date_receipt_line UNIQUE (store_id, sold_date, receipt_no, line_no)
);
CREATE INDEX idx_pos_sale_line_store_date ON pos_sale_line(store_id, sold_date);
CREATE INDEX idx_pos_sale_line_menu ON pos_sale_line(menu_id);

CREATE TABLE stock_count (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store(id),
    ingredient_id   BIGINT NOT NULL REFERENCES ingredient(id),
    counted_at      TIMESTAMPTZ NOT NULL,
    qty             NUMERIC(14, 3) NOT NULL,  -- 사장님이 확정한 실제 양

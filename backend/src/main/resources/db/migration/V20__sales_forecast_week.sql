-- 이번 주 매출 예측 (S15P31A308-267 · 226). AI 배치(weglee_ai.sales_forecast)가 가게 · 주마다 한 줄 쓰고, BE 는 읽기만 한다.
-- 상권 유동인구 모델의 결과를 가게 구(store.sigungu) 단위로 묶은 값이다. model 열로 어떤 모델이 냈는지 남겨 모델을 바꿔도 표는 그대로 쓴다.
CREATE TABLE sales_forecast_week (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES store (id),
    week_start      DATE NOT NULL,           -- 그 주 월요일
    model           VARCHAR(50) NOT NULL,    -- 예: 'seoulevent-v2'
    pct             INTEGER NOT NULL,        -- 평소 주 대비 %
    reason          VARCHAR(200) NOT NULL,   -- 가장 큰 이유 한 줄
    days            JSONB NOT NULL,          -- [{date, label, value}] value = 평소 100 기준 지수
    factors         JSONB NOT NULL,          -- [{name, note, pct}]
    analysis        TEXT,                    -- 설명 문장. 아직 만들지 않으면 NULL
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_sales_forecast_week UNIQUE (store_id, week_start)
);

COMMENT ON TABLE sales_forecast_week IS '가게별 이번 주 매출 예측(상권 유동인구 · 행사 기반). AI 배치가 (store_id, week_start) 로 덮어쓰고 GET /sales-forecast/this-week 가 읽는다. 근거: S15P31A308-267 · 226.';
